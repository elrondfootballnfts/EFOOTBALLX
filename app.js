function toHexNonce(nonce) {
  let hex = Number(nonce).toString(16);
  if (hex.length % 2 !== 0) hex = "0" + hex;
  return hex;
}

async function loadNftFromChain(collection, nonce) {
  const loadingOverlay = document.getElementById("canvas-loading");
  if (loadingOverlay) loadingOverlay.classList.remove("hidden");

  const maxNonce = collection === "GOALKEEPER-cb9e3e" ? 51 : 628;
  const clampedNonce = Math.max(1, Math.min(maxNonce, Number(nonce) || 1));
  const nonceInput = document.getElementById("nft-nonce-input");
  if (nonceInput) {
    nonceInput.value = clampedNonce;
    nonceInput.max = maxNonce;
  }

  const nftId = `${collection}-${toHexNonce(clampedNonce)}`;
  try {
    const res = await fetch(`https://api.multiversx.com/nfts/${nftId}`);
    if (!res.ok) throw new Error(`NFT ${nftId} not found`);
    const data = await res.json();

    const rawImageUrl =
      (data.media && data.media[0] && (data.media[0].url || data.media[0].originalUrl)) ||
      data.url;

    currentNftMeta = {
      name: data.name || `${collection} #${clampedNonce}`,
      identifier: data.identifier || nftId,
      url: rawImageUrl,
      attributes: (data.metadata && data.metadata.attributes) || []
    };

    renderNftTraits(currentNftMeta);
    await loadImageForCanvas(rawImageUrl);
  } catch (err) {
    console.warn("Fallback to local collection emblem:", err);
    const fallbackLocal =
      collection === "GOALKEEPER-cb9e3e"
        ? "branding/original/GOALKEEPER-cb9e3e/logo.png"
        : "branding/original/EFOOTBALL-91a4eb/logo.png";
    await loadImageForCanvas(fallbackLocal);
  }
}

function renderNftTraits(meta) {
  const nameEl = document.getElementById("loaded-nft-name");
  const linkEl = document.getElementById("loaded-nft-link");
  const chipsEl = document.getElementById("traits-chips");

  if (nameEl) nameEl.textContent = `${meta.name} (${meta.identifier})`;
  if (linkEl) linkEl.href = `https://explorer.multiversx.com/nfts/${meta.identifier}`;
  if (!chipsEl) return;

  chipsEl.innerHTML = "";
  const shownTraits = (meta.attributes || []).filter(
    (t) => t.trait_type && t.value && t.trait_type !== "BASEPLAYER" && t.trait_type !== "BASE_PLAYER"
  );

  shownTraits.slice(0, 6).forEach((t) => {
    const chip = document.createElement("div");
    chip.className = "trait-chip";
    chip.innerHTML = `<span>${t.trait_type}:</span> <strong>${String(t.value).trim()}</strong>`;
    chipsEl.appendChild(chip);
  });
}

function loadImageForCanvas(rawUrl) {
  return new Promise((resolve) => {
    const loadingOverlay = document.getElementById("canvas-loading");
    const img = new Image();
    img.crossOrigin = "anonymous";

    img.onload = () => {
      currentNftImage = img;
      if (loadingOverlay) loadingOverlay.classList.add("hidden");
      drawMemeCanvas();
      resolve();
    };

    img.onerror = () => {
      // Fallback to local high-res logo if remote gateway fails
      const fallbackImg = new Image();
      fallbackImg.onload = () => {
        currentNftImage = fallbackImg;
        if (loadingOverlay) loadingOverlay.classList.add("hidden");
        drawMemeCanvas();
        resolve();
      };
      fallbackImg.src = "branding/original/assests-2022/logo.png";
    };

    img.src = toCorsImageUrl(rawUrl, 700);
  });
}

function wrapCanvasText(ctx, text, maxWidth) {
  const words = text.toUpperCase().split(" ");
  const lines = [];
  let currentLine = words[0] || "";

  for (let i = 1; i < words.length; i++) {
    const word = words[i];
    const width = ctx.measureText(currentLine + " " + word).width;
    if (width < maxWidth) {
      currentLine += " " + word;
    } else {
      lines.push(currentLine);
      currentLine = word;
    }
  }
  if (currentLine) lines.push(currentLine);
  return lines;
}

function drawMemeCanvas() {
  const canvas = document.getElementById("meme-canvas");
  if (!canvas) return;
  const ctx = canvas.getContext("2d");
  const W = canvas.width;
  const H = canvas.height;

  ctx.fillStyle = "#08120c";
  ctx.fillRect(0, 0, W, H);

  if (currentNftImage) {
    ctx.drawImage(currentNftImage, 0, 0, W, H);
  }

  const topGrad = ctx.createLinearGradient(0, 0, 0, 175);
  topGrad.addColorStop(0, "rgba(0,0,0,0.75)");
  topGrad.addColorStop(1, "rgba(0,0,0,0)");
  ctx.fillStyle = topGrad;
  ctx.fillRect(0, 0, W, 175);

  const botGrad = ctx.createLinearGradient(0, H - 195, 0, H);
  botGrad.addColorStop(0, "rgba(0,0,0,0)");
  botGrad.addColorStop(1, "rgba(0,0,0,0.82)");
  ctx.fillStyle = botGrad;
  ctx.fillRect(0, H - 195, W, 195);

  const topText = (document.getElementById("meme-top-input")?.value || "").trim();
  const bottomText = (document.getElementById("meme-bottom-input")?.value || "").trim();

  ctx.font = "700 44px 'Bebas Neue', Impact, sans-serif";
  ctx.textAlign = "center";
  ctx.lineJoin = "round";
  ctx.lineWidth = 8;
  ctx.strokeStyle = "#000000";
  ctx.fillStyle = "#ffffff";

  if (topText) {
    const topLines = wrapCanvasText(ctx, topText, W - 50);
    topLines.forEach((line, index) => {
      const y = 56 + index * 46;
      ctx.strokeText(line, W / 2, y);
      ctx.fillText(line, W / 2, y);
    });
  }

  if (bottomText) {
    const botLines = wrapCanvasText(ctx, bottomText, W - 50);
    const startY = H - 48 - (botLines.length - 1) * 46;
    botLines.forEach((line, index) => {
      const y = startY + index * 46;
      ctx.strokeText(line, W / 2, y);
      ctx.fillStyle = "#a8ff00";
      ctx.fillText(line, W / 2, y);
    });
  }

  ctx.font = "700 15px 'JetBrains Mono', monospace";
  ctx.textAlign = "right";
  ctx.fillStyle = "rgba(7, 11, 9, 0.85)";
  ctx.fillRect(W - 305, H - 30, 295, 22);
  ctx.fillStyle = "#a8ff00";
  ctx.fillText("⚽ $EFOO • SUNDAY LEAGUE DEGEN FC", W - 16, H - 14);
}

