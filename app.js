function drawMemeCanvas() {
  const canvas = document.getElementById("meme-canvas");
  if (!canvas) return;
  const ctx = canvas.getContext("2d");
  const W = canvas.width;
  const H = canvas.height;

  ctx.fillStyle = "#08120c";
  ctx.fillRect(0, 0, W, H);

  if (currentNftImage) {
    ctx.drawImage(currentNftImage, 0, 0, W, H);
  }

  const topGrad = ctx.createLinearGradient(0, 0, 0, 175);
  topGrad.addColorStop(0, "rgba(0,0,0,0.75)");
  topGrad.addColorStop(1, "rgba(0,0,0,0)");
  ctx.fillStyle = topGrad;
  ctx.fillRect(0, 0, W, 175);

  const botGrad = ctx.createLinearGradient(0, H - 195, 0, H);
  botGrad.addColorStop(0, "rgba(0,0,0,0)");
  botGrad.addColorStop(1, "rgba(0,0,0,0.82)");
  ctx.fillStyle = botGrad;
  ctx.fillRect(0, H - 195, W, 195);

  const topText = (document.getElementById("meme-top-input")?.value || "").trim();
  const bottomText = (document.getElementById("meme-bottom-input")?.value || "").trim();

  ctx.font = "700 44px 'Bebas Neue', Impact, sans-serif";
  ctx.textAlign = "center";
  ctx.lineJoin = "round";
  ctx.lineWidth = 8;
  ctx.strokeStyle = "#000000";
  ctx.fillStyle = "#ffffff";

  if (topText) {
    const topLines = wrapCanvasText(ctx, topText, W - 50);
    topLines.forEach((line, index) => {
      const y = 56 + index * 46;
      ctx.strokeText(line, W / 2, y);
      ctx.fillText(line, W / 2, y);
    });
  }

  if (bottomText) {
    const botLines = wrapCanvasText(ctx, bottomText, W - 50);
    const startY = H - 48 - (botLines.length - 1) * 46;
    botLines.forEach((line, index) => {
      const y = startY + index * 46;
      ctx.strokeText(line, W / 2, y);
      ctx.fillStyle = "#a8ff00";
      ctx.fillText(line, W / 2, y);
    });
  }

  // 3D Stadium Glass Watermark Pill Badge with Official $EFOO Token Logo
  const badgeW = 295;
  const badgeH = 26;
  const badgeX = W - badgeW - 14;
  const badgeY = H - badgeH - 12;

  ctx.save();
  ctx.fillStyle = "rgba(6, 14, 10, 0.88)";
  ctx.strokeStyle = "rgba(168, 255, 0, 0.4)";
  ctx.lineWidth = 1;
  ctx.beginPath();
  if (typeof ctx.roundRect === "function") {
    ctx.roundRect(badgeX, badgeY, badgeW, badgeH, 13);
  } else {
    ctx.rect(badgeX, badgeY, badgeW, badgeH);
  }
  ctx.fill();
  ctx.stroke();

  // Draw circular $EFOO token logo
  const logoSize = 18;
  const logoX = badgeX + 6;
  const logoY = badgeY + (badgeH - logoSize) / 2;
  if (efooWatermarkLogo.complete && efooWatermarkLogo.naturalWidth > 0) {
    ctx.save();
    ctx.beginPath();
    ctx.arc(logoX + logoSize / 2, logoY + logoSize / 2, logoSize / 2, 0, Math.PI * 2);
    ctx.clip();
    ctx.drawImage(efooWatermarkLogo, logoX, logoY, logoSize, logoSize);
    ctx.restore();
  }

  ctx.font = "800 13px 'JetBrains Mono', monospace";
  ctx.textAlign = "left";
  ctx.fillStyle = "#a8ff00";
  ctx.fillText("$EFOO • SUNDAY LEAGUE DEGEN FC", logoX + logoSize + 8, badgeY + 17);
  ctx.restore();
}

