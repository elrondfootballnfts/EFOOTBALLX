function shootPenalty(targetZone) {
  if (gameState.isShooting) return;
  gameState.isShooting = true;

  const ball = document.getElementById("ball-sprite");
  const goalie = document.getElementById("goalie-sprite");
  const comm = document.getElementById("game-commentary");

  const zones = ["tl", "tr", "c", "bl", "br"];
  const coords = {
    tl: { left: "10%", bottom: "165px" },
    tr: { left: "78%", bottom: "165px" },
    c:  { left: "44%", bottom: "155px" },
    bl: { left: "10%", bottom: "18px" },
    br: { left: "78%", bottom: "18px" }
  };

  // Player NFT increases accuracy (reduces chance goalkeeper guesses right)
  const hasPlayer = walletState.playersCount >= 1;
  const hasKeeper = walletState.keepersCount >= 1;
  const hasEfoo = walletState.efooBalance >= 1000000;

  let goalieChoice = zones[Math.floor(Math.random() * zones.length)];
  if (hasPlayer && goalieChoice === targetZone && Math.random() < 0.45) {
    // Striker NFT curve fakes out the keeper!
    goalieChoice = zones.find((z) => z !== targetZone) || "c";
  }

  // Animate Ball & Goalie
  if (ball && coords[targetZone]) {
    ball.style.left = coords[targetZone].left;
    ball.style.bottom = coords[targetZone].bottom;
    ball.style.transform = "scale(0.68) rotate(360deg)";
  }
  if (goalie && coords[goalieChoice]) {
    goalie.style.left = coords[goalieChoice].left;
    goalie.style.bottom = coords[goalieChoice].bottom;
  }

  setTimeout(() => {
    let isGoal = targetZone !== goalieChoice;

    // Goalkeeper NFT Shield saves your streak once if blocked!
    if (!isGoal && gameState.shieldAvailable) {
      gameState.shieldAvailable = false;
      isGoal = true;
      if (comm) {
        comm.innerHTML =
          currentLang === "ro"
            ? "🧤 <strong>SCUTUL PORTARULUI NFT ACTIVAT!</strong> Mingea a ricoșat din bară direct în poartă!"
            : "🧤 <strong>GOALKEEPER NFT SHIELD TRIGGERED!</strong> Ball ricocheted off the post and went IN!";
      }
    } else if (isGoal) {
      gameState.goals += 1;
      gameState.streak += 1;
      const mult = hasKeeper ? 3 : hasPlayer ? 2 : 1;
      const rocketBonus = hasEfoo ? 500 : 0;
      const pts = (1000 + gameState.streak * 250) * mult + rocketBonus;
      gameState.score += pts;

      if (gameState.score > gameState.bestScore) {
        gameState.bestScore = gameState.score;
        localStorage.setItem("efoo_fomo_best", String(gameState.bestScore));
      }

      if (comm) {
        comm.innerHTML =
          currentLang === "ro"
            ? `⚽🔥 <strong>GOOOOL ÎN VINCLU!</strong> +${pts.toLocaleString()} puncte $EFOO (Serie: ${gameState.streak}x)!`
            : `⚽🔥 <strong>TOP BINS GOOOL!</strong> +${pts.toLocaleString()} $EFOO pts (Streak: ${gameState.streak}x)!`;
      }
    } else {
      gameState.streak = 0;
      gameState.shieldAvailable = hasKeeper; // Reset shield for next streak
      if (comm) {
        comm.innerHTML =
          currentLang === "ro"
            ? "🧤❌ <strong>APĂRĂ PORTARUL!</strong> Seria s-a resetat — mai bagă o fisă în Liga de Duminică!"
            : "🧤❌ <strong>SAVED BY THE KEEPER!</strong> Streak reset — take another Sunday League shot!";
      }
    }

    document.getElementById("game-goals").textContent = String(gameState.goals);
    document.getElementById("game-streak").textContent = String(gameState.streak);
    document.getElementById("game-score").textContent = gameState.score.toLocaleString("en-US");
    document.getElementById("game-best").textContent = gameState.bestScore.toLocaleString("en-US");

    // Reset positions after 900ms
    setTimeout(() => {
      if (ball) {
        ball.style.left = "calc(50% - 28px)";
        ball.style.bottom = "-62px";
        ball.style.transform = "scale(1) rotate(0deg)";
      }
      if (goalie) {
        goalie.style.left = "calc(50% - 45px)";
        goalie.style.bottom = "6px";
      }
      gameState.isShooting = false;
    }, 850);
  }, 420);
}

